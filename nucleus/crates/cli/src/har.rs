//! `--rules-from-har`: turns a HAR recording of a real exchange (e.g. a C2 session captured
//! where the server was still alive) into a Camel rule that replays it: requests are matched
//! by method, host and path, and several recorded responses to the same request are played
//! back in order, per sample (via the daemon's `state` bean).

use std::collections::BTreeMap;

use anyhow::{bail, Context as _};
use base64::Engine as _;
use serde_json::Value;

/// Hop-by-hop & framing headers: the nucleus frames the response itself
const DROPPED: &[&str] = &["content-length", "transfer-encoding", "content-encoding", "connection", "keep-alive"];

/// "GET c2.example /gate.php" -> recorded raw responses, in order
pub fn exchanges(har: &Value) -> anyhow::Result<BTreeMap<String, Vec<Vec<u8>>>> {
    let entries = har.pointer("/log/entries").and_then(Value::as_array).context("not a HAR file (no log.entries)")?;
    let mut out: BTreeMap<String, Vec<Vec<u8>>> = BTreeMap::new();
    for entry in entries {
        let method = entry.pointer("/request/method").and_then(Value::as_str).unwrap_or("GET").to_ascii_uppercase();
        let url = entry.pointer("/request/url").and_then(Value::as_str).unwrap_or_default();
        let Some(rest) = url.split_once("://").map(|(_, r)| r) else { continue };
        let (authority, path) = rest.split_at(rest.find('/').unwrap_or(rest.len()));
        let host = authority.rsplit('@').next().unwrap_or(authority).split(':').next().unwrap_or("").to_ascii_lowercase();
        let path = path.split(['?', '#']).next().filter(|p| !p.is_empty()).unwrap_or("/");
        let response = &entry["response"];
        let status = response["status"].as_u64().unwrap_or(200);
        let reason = response["statusText"].as_str().filter(|r| !r.is_empty()).unwrap_or("OK");
        let mut raw = format!("HTTP/1.1 {status} {reason}\r\n").into_bytes();
        for header in response["headers"].as_array().into_iter().flatten() {
            let (Some(name), Some(value)) = (header["name"].as_str(), header["value"].as_str()) else { continue };
            if name.starts_with(':') || DROPPED.contains(&name.to_ascii_lowercase().as_str()) || name.contains(['\r', '\n']) || value.contains(['\r', '\n']) {
                continue;
            }
            raw.extend(format!("{name}: {value}\r\n").bytes());
        }
        raw.extend(b"\r\n");
        let content = &response["content"];
        if let Some(text) = content["text"].as_str() {
            if content["encoding"].as_str() == Some("base64") {
                raw.extend(base64::engine::general_purpose::STANDARD.decode(text.trim()).context("bad base64 body in the HAR")?);
            } else {
                raw.extend(text.as_bytes());
            }
        }
        out.entry(format!("{method} {host} {path}")).or_default().push(raw);
    }
    if out.is_empty() {
        bail!("the HAR file has no usable entries");
    }
    Ok(out)
}

fn groovy_string(text: &str) -> String {
    format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// The Camel YAML route (`direct:decide-recorded`)
pub fn rules(har: &Value, source: &str) -> anyhow::Result<String> {
    let exchanges = exchanges(har)?;
    let mut out = format!(
        "# Generated by fakenet-nucleus --rules-from-har from {}: replays the recorded\n\
         # responses. Requests are matched by method, host & path; several responses to one\n\
         # request are played in order for each sample (then the last one repeats).\n\
         # Use it: copy into routes/, then add `- to: direct:decide-recorded` to decide-http\n\
         # (requests it doesn't know keep the other rules' answer, or the default).\n\
         - route:\n    id: decide-recorded\n    from:\n      uri: direct:decide-recorded\n      steps:\n        - setBody:\n            groovy: |\n              def recorded = [\n",
        source.replace('\n', " ")
    );
    for (key, responses) in &exchanges {
        let encoded: Vec<String> = responses.iter().map(|r| groovy_string(&base64::engine::general_purpose::STANDARD.encode(r))).collect();
        out.push_str(&format!("                {}: [{}],\n", groovy_string(key), encoded.join(", ")));
    }
    out.push_str(
        "              ]\n\
         \x20             def host = (request.headers.FakenetHost ?: '').split(':')[0].toLowerCase()\n\
         \x20             def path = ((request.headers.FakenetPath ?: '/') as String).split('[?#]')[0] ?: '/'\n\
         \x20             def key = \"${request.headers.FakenetMethod} ${host} ${path}\".toString()\n\
         \x20             def responses = recorded[key]\n\
         \x20             if (!responses) return request.body\n\
         \x20             def state = camelContext.registry.lookupByName('state')\n\
         \x20             def n = state.increment(request.headers.FakenetActor ?: 'unknown', 'recorded ' + key)\n\
         \x20             request.setHeader('FakenetRoute', 'recorded')\n\
         \x20             responses[Math.min(n - 1, responses.size() - 1) as int].decodeBase64()\n",
    );
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn turns_a_har_into_ordered_replay_rules() {
        let har = serde_json::json!({ "log": { "entries": [
            { "request": { "method": "GET", "url": "http://C2.Example:8080/gate.php?id=1" },
              "response": { "status": 200, "statusText": "OK", "headers": [{ "name": "Content-Length", "value": "9" }, { "name": "X-Task", "value": "1" }],
                            "content": { "text": "register!" } } },
            { "request": { "method": "GET", "url": "http://c2.example/gate.php?id=2" },
              "response": { "status": 200, "headers": [], "content": { "text": "AAEC", "encoding": "base64" } } },
            { "request": { "method": "POST", "url": "https://c2.example/upload" },
              "response": { "status": 404, "statusText": "Not Found", "headers": [{ "name": "Evil\r\nInjected", "value": "x" }], "content": {} } }
        ]}});
        let exchanges = exchanges(&har).unwrap();
        let gate = &exchanges["GET c2.example /gate.php"];
        assert_eq!(gate.len(), 2);
        assert_eq!(gate[0], b"HTTP/1.1 200 OK\r\nX-Task: 1\r\n\r\nregister!");
        assert_eq!(gate[1], b"HTTP/1.1 200 OK\r\n\r\n\x00\x01\x02");
        assert_eq!(exchanges["POST c2.example /upload"][0], b"HTTP/1.1 404 Not Found\r\n\r\n");
        let yaml = rules(&har, "test.har").unwrap();
        assert!(yaml.contains("id: decide-recorded") && yaml.contains("'GET c2.example /gate.php': ['"));
        assert!(rules(&serde_json::json!({}), "x").is_err());
    }
}
